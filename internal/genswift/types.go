package genswift

import (
	"strings"

	"github.com/1homsi/onekit/internal/onkir"
)

func GenerateTypes(file *onkir.File) []byte {
	return GenerateTypesInNamespace(file, "", nil)
}

func GenerateTypesInNamespace(file *onkir.File, namespace string, resolver PackageResolver) []byte {
	p := newPrinter(resolver)
	p.P("// Code generated by onek. DO NOT EDIT.")
	p.P()
	p.P("import Foundation")
	p.P()
	if namespace != "" {
		p.P("public enum ", namespace, " {}")
		p.P()
		p.P("extension ", namespace, " {")
		p.Indent()
	}
	for _, e := range fileEnumsDeep(file) {
		writeEnum(p, e)
	}
	for _, m := range fileMessagesDeep(file) {
		writeMessage(p, m)
	}
	if namespace != "" {
		p.Dedent()
		p.P("}")
	}
	return p.Bytes()
}

func isDeprecatedField(f *onkir.Field) bool {
	_, ok := f.Deprecated()
	return ok
}

func storageName(f *onkir.Field) string {
	if isDeprecatedField(f) {
		return "_" + Ident(f.Name)
	}
	return Ident(f.Name)
}

func writeDoc(p *Printer, doc string) {
	if doc = strings.TrimSpace(doc); doc == "" {
		return
	}
	for line := range strings.SplitSeq(doc, "\n") {
		if line = strings.TrimRight(line, " \t"); line == "" {
			p.P("///")
		} else {
			p.P("/// ", line)
		}
	}
}

func writeDeprecated(p *Printer, deprecated func() (string, bool)) {
	reason, ok := deprecated()
	if !ok {
		return
	}
	if reason == "" {
		reason = "no longer supported"
	}
	p.P("@available(*, deprecated, message: ", swiftString(reason), ")")
}

func writeEnum(p *Printer, e *onkir.Enum) {
	name := EnumName(e)
	writeDoc(p, e.Doc)
	p.P("public enum ", name, ": String, CaseIterable, Sendable {")
	p.Indent()
	for _, v := range e.Values {
		writeDoc(p, v.Doc)
		p.P("case ", EnumCaseName(v), " = ", swiftString(v.JSONName()))
	}
	p.P()
	p.P("public var ordinal: Int { Self.allCases.firstIndex(of: self) ?? 0 }")
	p.P()
	p.P("public static func fromWire(_ value: Any?) throws -> ", name, " {")
	p.Indent()
	p.P("if let text = value as? String, let known = ", name, "(rawValue: text) { return known }")
	p.P("throw OnekitError.decoding(", swiftString("unknown "+e.Name+" value: "), " + String(describing: value))")
	p.Dedent()
	p.P("}")
	p.Dedent()
	p.P("}")
	p.P()
}

func (p *Printer) elemType(t *onkir.Type) string {
	switch t.Kind {
	case onkir.KindMessage:
		return p.messageRef(t.Message)
	case onkir.KindEnum:
		return p.enumRef(t.Enum)
	case onkir.KindMap:
		return "[String: " + p.elemType(t.MapValue) + "]"
	case onkir.KindScalar:
		switch t.Scalar {
		case onkir.ScalarString:
			return "String"
		case onkir.ScalarBool:
			return "Bool"
		case onkir.ScalarInt32:
			return "Int32"
		case onkir.ScalarUint32:
			return "UInt32"
		case onkir.ScalarInt64:
			return "Int64"
		case onkir.ScalarUint64:
			return "UInt64"
		case onkir.ScalarFloat32:
			return "Float"
		case onkir.ScalarFloat64:
			return "Double"
		case onkir.ScalarBytes:
			return "Data"
		case onkir.ScalarTimestamp:
			return "Date"
		case onkir.ScalarJSON:
			return "Any?"
		}
	}
	return "Any?"
}

func isJSONScalar(t *onkir.Type) bool {
	return t != nil && t.Kind == onkir.KindScalar && t.Scalar == onkir.ScalarJSON
}

func isNullableKind(f *onkir.Field) bool {
	if f.Oneof != nil {
		return true
	}
	if f.Repeated || f.Type.Kind == onkir.KindMap {
		return false
	}
	if f.Optional || f.Type.Kind == onkir.KindMessage {
		return true
	}
	return f.Type.Kind == onkir.KindScalar && (f.Type.Scalar == onkir.ScalarTimestamp || f.Type.Scalar == onkir.ScalarJSON)
}

func (p *Printer) fieldType(m *onkir.Message, f *onkir.Field) string {
	if f.Oneof != nil {
		return OneofTypeName(m, f) + "?"
	}
	elem := p.elemType(f.Type)
	switch {
	case f.Repeated:
		return "[" + elem + "]"
	case f.Type.Kind == onkir.KindMap:
		return elem
	case isNullableKind(f) && !strings.HasSuffix(elem, "?"):
		return elem + "?"
	}
	return elem
}

func (p *Printer) defaultValue(t *onkir.Type) string {
	switch t.Kind {
	case onkir.KindEnum:
		return p.enumRef(t.Enum) + "." + EnumCaseName(t.Enum.Values[0])
	case onkir.KindMessage:
		return "try " + p.messageRef(t.Message) + "(json: [String: Any]())"
	case onkir.KindMap:
		return "[:]"
	case onkir.KindScalar:
		switch t.Scalar {
		case onkir.ScalarString:
			return `""`
		case onkir.ScalarBool:
			return "false"
		case onkir.ScalarInt32, onkir.ScalarUint32, onkir.ScalarInt64, onkir.ScalarUint64, onkir.ScalarFloat32, onkir.ScalarFloat64:
			return "0"
		case onkir.ScalarBytes:
			return "Data()"
		}
	}
	return "nil"
}

func (p *Printer) initDefault(f *onkir.Field) string {
	switch {
	case isNullableKind(f):
		return "nil"
	case f.Repeated:
		return "[]"
	case f.Type.Kind == onkir.KindMap:
		return "[:]"
	}
	return p.defaultValue(f.Type)
}

func encodeValue(t *onkir.Type, f *onkir.Field, expr string, inMap bool) string {
	switch t.Kind {
	case onkir.KindMessage:
		return expr + ".toJSONValue()"
	case onkir.KindEnum:
		if !inMap && enumAsNumber(f) {
			return expr + ".ordinal"
		}
		return expr + ".rawValue"
	case onkir.KindMap:
		inner := encodeValue(t.MapValue, nil, "v", true)
		if inner == "v" {
			return expr
		}
		return expr + ".mapValues { v in " + inner + " }"
	case onkir.KindScalar:
		switch t.Scalar {
		case onkir.ScalarInt64, onkir.ScalarUint64:
			if !inMap && (f == nil || int64AsString(f)) {
				return "String(" + expr + ")"
			}
		case onkir.ScalarFloat32:
			return "Double(" + expr + ")"
		case onkir.ScalarBytes:
			enc := ""
			if !inMap {
				enc = bytesEncoding(f)
			}
			return "onekitBytesEncode(" + expr + ", " + swiftString(enc) + ")"
		case onkir.ScalarTimestamp:
			enc := ""
			if !inMap {
				enc = timestampEncoding(f)
			}
			return "onekitTimeEncode(" + expr + ", " + swiftString(enc) + ")"
		}
	}
	return expr
}

func (p *Printer) decodeValue(t *onkir.Type, f *onkir.Field, expr string, inMap bool) string {
	switch t.Kind {
	case onkir.KindMessage:
		return p.messageRef(t.Message) + "(json: " + expr + ")"
	case onkir.KindEnum:
		if !inMap && enumAsNumber(f) {
			return "onekitEnumByIndex(" + p.enumRef(t.Enum) + ".self, " + expr + ")"
		}
		return p.enumRef(t.Enum) + ".fromWire(" + expr + ")"
	case onkir.KindMap:
		inner := p.decodeValue(t.MapValue, nil, "v", true)
		return "onekitMap(" + expr + ") { v in " + tryPrefix(inner) + inner + " }"
	case onkir.KindScalar:
		switch t.Scalar {
		case onkir.ScalarString:
			return "onekitString(" + expr + ")"
		case onkir.ScalarBool:
			return "onekitBool(" + expr + ")"
		case onkir.ScalarInt32:
			return "onekitInt32(" + expr + ")"
		case onkir.ScalarUint32:
			return "onekitUInt32(" + expr + ")"
		case onkir.ScalarInt64:
			return "onekitInt64(" + expr + ")"
		case onkir.ScalarUint64:
			return "onekitUInt64(" + expr + ")"
		case onkir.ScalarFloat32:
			return "Float(onekitDouble(" + expr + "))"
		case onkir.ScalarFloat64:
			return "onekitDouble(" + expr + ")"
		case onkir.ScalarBytes:
			enc := ""
			if !inMap {
				enc = bytesEncoding(f)
			}
			return "onekitBytesDecode(" + expr + ", " + swiftString(enc) + ")"
		case onkir.ScalarTimestamp:
			enc := ""
			if !inMap {
				enc = timestampEncoding(f)
			}
			return "onekitTimeDecode(" + expr + ", " + swiftString(enc) + ")"
		case onkir.ScalarJSON:
			return "onekitNonNull(" + expr + ")"
		}
	}
	return expr
}

func tryPrefix(expr string) string {
	if strings.HasPrefix(expr, "onekitNonNull(") {
		return ""
	}
	return "try "
}

func fieldWireValue(f *onkir.Field, expr string) string {
	if f.Repeated {
		inner := encodeValue(f.Type, f, "v", false)
		if inner == "v" {
			return expr
		}
		return expr + ".map { v in " + inner + " }"
	}
	return encodeValue(f.Type, f, expr, false)
}

func (p *Printer) fieldFromWire(f *onkir.Field, expr string) string {
	if f.Repeated {
		inner := p.decodeValue(f.Type, f, "v", false)
		return "onekitList(" + expr + ") { v in " + tryPrefix(inner) + inner + " }"
	}
	return p.decodeValue(f.Type, f, expr, false)
}

func writeMessage(p *Printer, m *onkir.Message) {
	name := MessageName(m)
	root := rootUnwrapField(m)
	writeDoc(p, m.Doc)
	conformances := "OnekitMessage, Equatable, CustomStringConvertible"
	if m.IsError() {
		conformances += ", Error, @unchecked Sendable"
	}
	p.P("public final class ", name, ": ", conformances, " {")
	p.Indent()
	for _, f := range m.Fields {
		writeDoc(p, f.Doc)
		if isDeprecatedField(f) {
			p.P("private var ", storageName(f), ": ", p.fieldType(m, f))
			writeDeprecated(p, f.Deprecated)
			p.P("public var ", Ident(f.Name), ": ", p.fieldType(m, f), " {")
			p.Indent()
			p.P("get { ", storageName(f), " }")
			p.P("set { ", storageName(f), " = newValue }")
			p.Dedent()
			p.P("}")
			continue
		}
		p.P("public var ", Ident(f.Name), ": ", p.fieldType(m, f))
	}
	if len(m.Fields) > 0 {
		p.P()
	}
	writeInit(p, m)
	if root != nil {
		writeRootUnwrapCodec(p, root)
	} else {
		writeFromJSON(p, m)
		writeToJSON(p, m)
	}
	writeValidate(p, m)
	p.P("public static func == (lhs: ", name, ", rhs: ", name, ") -> Bool {")
	p.Indent()
	p.P("onekitJSONEquals(lhs.toJSONValue(), rhs.toJSONValue())")
	p.Dedent()
	p.P("}")
	p.P()
	p.P("public var description: String { ", swiftString(name+"("), " + String(describing: toJSONValue()) + \")\" }")
	p.Dedent()
	p.P("}")
	p.P()
	for _, f := range m.Fields {
		if f.Oneof != nil {
			writeOneof(p, m, f)
		}
	}
}

func writeInit(p *Printer, m *onkir.Message) {
	if len(m.Fields) == 0 {
		p.P("public init() {}")
		p.P()
		return
	}
	p.P("public init(")
	p.Indent()
	for i, f := range m.Fields {
		sep := ","
		if i == len(m.Fields)-1 {
			sep = ""
		}
		p.P(Ident(f.Name), ": ", p.fieldType(m, f), " = ", p.initDefault(f), sep)
	}
	p.Dedent()
	p.P(") {")
	p.Indent()
	for _, f := range m.Fields {
		p.P("self.", storageName(f), " = ", Ident(f.Name))
	}
	p.Dedent()
	p.P("}")
	p.P()
}

func writeToJSON(p *Printer, m *onkir.Message) {
	p.P("public func toJSON() -> [String: Any] {")
	p.Indent()
	if len(m.Fields) == 0 {
		p.P("[:]")
	} else {
		p.P("var json: [String: Any] = [:]")
		for _, f := range m.Fields {
			writeToJSONField(p, f)
		}
		p.P("return json")
	}
	p.Dedent()
	p.P("}")
	p.P()
	p.P("public func toJSONValue() -> Any { toJSON() }")
	p.P()
}

func zeroCheck(f *onkir.Field, id string) string {
	switch f.Type.Scalar {
	case onkir.ScalarString:
		return "!" + id + ".isEmpty"
	case onkir.ScalarBool:
		return id
	case onkir.ScalarBytes:
		return "!" + id + ".isEmpty"
	}
	return id + " != 0"
}

func writeToJSONField(p *Printer, f *onkir.Field) {
	id := "self." + storageName(f)
	key := swiftString(f.Name)
	if f.Oneof != nil {
		p.P("if let value = ", id, " { json[", key, "] = value.toJSON() }")
		return
	}
	switch {
	case f.Repeated, f.Type.Kind == onkir.KindMap:
		p.P("if !", id, ".isEmpty { json[", key, "] = ", fieldWireValue(f, id), " }")
	case f.Type.Kind == onkir.KindMessage:
		writeMessageFieldToJSON(p, f)
	case f.Optional, f.Type.Kind == onkir.KindEnum, int64AsString(f):
		if isNullableKind(f) {
			p.P("if let value = ", id, " { json[", key, "] = ", encodeValue(f.Type, f, "value", false), " }")
		} else {
			p.P("json[", key, "] = ", encodeValue(f.Type, f, id, false))
		}
	case f.Type.Kind == onkir.KindScalar && (f.Type.Scalar == onkir.ScalarTimestamp || f.Type.Scalar == onkir.ScalarJSON):
		p.P("if let value = ", id, " { json[", key, "] = ", encodeValue(f.Type, f, "value", false), " }")
	default:
		p.P("if ", zeroCheck(f, id), " { json[", key, "] = ", encodeValue(f.Type, f, id, false), " }")
	}
}

func writeMessageFieldToJSON(p *Printer, f *onkir.Field) {
	id := "self." + storageName(f)
	key := swiftString(f.Name)
	if prefix, ok := flattenPrefix(f); ok {
		p.P("if let value = ", id, ", let object = value.toJSONValue() as? [String: Any] {")
		p.Indent()
		p.P("for (name, item) in object { json[", swiftString(prefix), " + name] = item }")
		p.Dedent()
		p.P("}")
		return
	}
	switch emptyBehavior(f) {
	case emptyBehaviorNull:
		p.P("if let value = ", id, " {")
		p.Indent()
		p.P("let object = value.toJSONValue()")
		p.P("json[", key, "] = onekitIsEmptyObject(object) ? NSNull() : object")
		p.Dedent()
		p.P("} else {")
		p.Indent()
		p.P("json[", key, "] = NSNull()")
		p.Dedent()
		p.P("}")
	case emptyBehaviorOmit:
		p.P("if let value = ", id, " {")
		p.Indent()
		p.P("let object = value.toJSONValue()")
		p.P("if !onekitIsEmptyObject(object) { json[", key, "] = object }")
		p.Dedent()
		p.P("}")
	default:
		p.P("if let value = ", id, " { json[", key, "] = value.toJSONValue() }")
	}
}

func writeFromJSON(p *Printer, m *onkir.Message) {
	if len(m.Fields) == 0 {
		p.P("public init(json value: Any?) throws {")
		p.Indent()
		p.P("_ = try onekitObject(value)")
		p.Dedent()
		p.P("}")
		p.P()
		return
	}
	p.P("public init(json value: Any?) throws {")
	p.Indent()
	p.P("let json = try onekitObject(value)")
	for _, f := range m.Fields {
		p.P("self.", storageName(f), " = ", p.fromJSONExpr(m, f))
	}
	p.Dedent()
	p.P("}")
	p.P()
}

func (p *Printer) fromJSONExpr(m *onkir.Message, f *onkir.Field) string {
	raw := "json[" + swiftString(f.Name) + "]"
	if f.Oneof != nil {
		return "try " + OneofTypeName(m, f) + ".fromJSON(" + raw + ")"
	}
	if prefix, ok := flattenPrefix(f); ok {
		return "try onekitHasPrefix(json, " + swiftString(prefix) + ") ? " + p.messageRef(f.Type.Message) +
			"(json: onekitStripPrefix(json, " + swiftString(prefix) + ")) : nil"
	}
	if !f.Repeated && isJSONScalar(f.Type) {
		return p.decodeValue(f.Type, f, raw, false)
	}
	decoded := p.fieldFromWire(f, raw)
	switch {
	case isNullableKind(f):
		return "try onekitIsNull(" + raw + ") ? nil : " + decoded
	case f.Repeated:
		return "try onekitIsNull(" + raw + ") ? [] : " + decoded
	case f.Type.Kind == onkir.KindMap:
		return "try onekitIsNull(" + raw + ") ? [:] : " + decoded
	}
	return "try onekitIsNull(" + raw + ") ? " + p.defaultValue(f.Type) + " : " + decoded
}

func writeRootUnwrapCodec(p *Printer, f *onkir.Field) {
	id := "self." + storageName(f)
	p.P("public func toJSONValue() -> Any {")
	p.Indent()
	if isNullableKind(f) {
		p.P("guard let value = ", id, " else { return NSNull() }")
		p.P("return ", encodeValue(f.Type, f, "value", false))
	} else {
		p.P("return ", fieldWireValue(f, id))
	}
	p.Dedent()
	p.P("}")
	p.P()
	p.P("public init(json value: Any?) throws {")
	p.Indent()
	decoded := p.fieldFromWire(f, "value")
	switch {
	case !f.Repeated && isJSONScalar(f.Type):
		p.P("self.", storageName(f), " = ", decoded)
	case isNullableKind(f):
		p.P("self.", storageName(f), " = try onekitIsNull(value) ? nil : ", decoded)
	case f.Repeated:
		p.P("self.", storageName(f), " = try onekitIsNull(value) ? [] : ", decoded)
	case f.Type.Kind == onkir.KindMap:
		p.P("self.", storageName(f), " = try onekitIsNull(value) ? [:] : ", decoded)
	default:
		p.P("self.", storageName(f), " = try onekitIsNull(value) ? ", p.defaultValue(f.Type), " : ", decoded)
	}
	p.Dedent()
	p.P("}")
	p.P()
}

func variantCaseName(v *onkir.OneofVariant) string {
	return Ident(v.Name)
}

func writeOneof(p *Printer, m *onkir.Message, f *onkir.Field) {
	base := OneofTypeName(m, f)
	disc := swiftString(oneofDiscriminator(f))
	flatten := f.Oneof.Flatten()
	p.P("public enum ", base, ": Equatable {")
	p.Indent()
	for _, v := range f.Oneof.Variants {
		p.P("case ", variantCaseName(v), "(", p.elemType(v.Type), ")")
	}
	p.P()
	p.P("public func toJSON() -> [String: Any] {")
	p.Indent()
	p.P("switch self {")
	for _, v := range f.Oneof.Variants {
		synthetic := &onkir.Field{Name: v.Name, Type: v.Type}
		tag := swiftString(v.Tag())
		if flatten {
			p.P("case .", variantCaseName(v), "(let value):")
			p.Indent()
			p.P("var json = (value.toJSONValue() as? [String: Any]) ?? [:]")
			p.P("json[", disc, "] = ", tag)
			p.P("return json")
			p.Dedent()
			continue
		}
		p.P("case .", variantCaseName(v), "(let value):")
		p.Indent()
		p.P("return [", disc, ": ", tag, ", ", swiftString(v.Name), ": ", encodeValue(v.Type, synthetic, "value", false), "]")
		p.Dedent()
	}
	p.P("}")
	p.Dedent()
	p.P("}")
	p.P()
	p.P("public static func fromJSON(_ value: Any?) throws -> ", base, "? {")
	p.Indent()
	p.P("guard let json = value as? [String: Any] else { return nil }")
	p.P("switch json[", disc, "] as? String {")
	for _, v := range f.Oneof.Variants {
		synthetic := &onkir.Field{Name: v.Name, Type: v.Type}
		p.P("case ", swiftString(v.Tag()), "?:")
		p.Indent()
		if flatten {
			p.P("return .", variantCaseName(v), "(try ", p.messageRef(v.Type.Message), "(json: json))")
		} else {
			raw := "json[" + swiftString(v.Name) + "]"
			if isJSONScalar(v.Type) {
				p.P("return .", variantCaseName(v), "(onekitNonNull(", raw, "))")
			} else {
				missing := p.defaultValue(v.Type)
				missing = strings.TrimPrefix(missing, "try ")
				p.P("return .", variantCaseName(v), "(try onekitIsNull(", raw, ") ? ", missing, " : ", p.decodeValue(v.Type, synthetic, raw, false), ")")
			}
		}
		p.Dedent()
	}
	p.P("default:")
	p.Indent()
	p.P("return nil")
	p.Dedent()
	p.P("}")
	p.Dedent()
	p.P("}")
	p.P()
	p.P("public static func == (lhs: ", base, ", rhs: ", base, ") -> Bool {")
	p.Indent()
	p.P("onekitJSONEquals(lhs.toJSON(), rhs.toJSON())")
	p.Dedent()
	p.P("}")
	p.Dedent()
	p.P("}")
	p.P()
}

func writeValidate(p *Printer, m *onkir.Message) {
	p.P("public func validate() -> [String] {")
	p.Indent()
	var body []func()
	for _, f := range m.Fields {
		body = append(body, validateField(p, f)...)
	}
	if len(body) == 0 {
		p.P("[]")
		p.Dedent()
		p.P("}")
		p.P()
		return
	}
	p.P("var violations: [String] = []")
	for _, emit := range body {
		emit()
	}
	p.P("return violations")
	p.Dedent()
	p.P("}")
	p.P()
}

func validateField(p *Printer, f *onkir.Field) []func() {
	var out []func()
	id := "self." + storageName(f)
	nested := func(expr string) {
		p.P("for issue in ", expr, ".validate() { violations.append(", swiftString(f.Name+": "), " + issue) }")
	}
	add := func(emit func()) { out = append(out, emit) }
	if f.Oneof != nil {
		for _, v := range f.Oneof.Variants {
			if v.Type.Kind != onkir.KindMessage {
				continue
			}
			add(func() {
				p.P("if case .", variantCaseName(v), "(let value)? = ", id, " {")
				p.Indent()
				nested("value")
				p.Dedent()
				p.P("}")
			})
		}
	}
	if f.HasDecorator("required") {
		msg := swiftString(f.Name + " is required")
		switch {
		case f.Repeated || f.Type != nil && f.Type.Kind == onkir.KindMap:
			add(func() { p.P("if ", id, ".isEmpty { violations.append(", msg, ") }") })
		case f.Oneof == nil && f.Type.Kind == onkir.KindScalar && f.Type.Scalar == onkir.ScalarString && !isNullableKind(f):
			add(func() { p.P("if ", id, ".isEmpty { violations.append(", msg, ") }") })
		case f.Oneof == nil && f.Type.Kind == onkir.KindScalar && f.Type.Scalar == onkir.ScalarString:
			add(func() { p.P("if ", id, " == nil || ", id, "!.isEmpty { violations.append(", msg, ") }") })
		case isNullableKind(f):
			add(func() {
				if isJSONScalar(f.Type) {
					p.P("if onekitIsNull(", id, ") { violations.append(", msg, ") }")
					return
				}
				p.P("if ", id, " == nil { violations.append(", msg, ") }")
			})
		}
	}
	if f.Oneof != nil {
		return out
	}
	if f.Repeated {
		if d, ok := f.Decorator("min_items"); ok {
			value, _ := d.Value()
			add(func() {
				p.P("if ", id, ".count < ", value, " { violations.append(", swiftString(f.Name+" must contain at least "+value+" items"), ") }")
			})
		}
		if d, ok := f.Decorator("max_items"); ok {
			value, _ := d.Value()
			add(func() {
				p.P("if ", id, ".count > ", value, " { violations.append(", swiftString(f.Name+" must contain at most "+value+" items"), ") }")
			})
		}
		if f.Type.Kind == onkir.KindMessage {
			add(func() {
				p.P("for item in ", id, " {")
				p.Indent()
				nested("item")
				p.Dedent()
				p.P("}")
			})
		}
		return out
	}
	switch f.Type.Kind {
	case onkir.KindMessage:
		add(func() {
			p.P("if let value = ", id, " {")
			p.Indent()
			nested("value")
			p.Dedent()
			p.P("}")
		})
		return out
	case onkir.KindMap:
		if f.Type.MapValue != nil && f.Type.MapValue.Kind == onkir.KindMessage {
			add(func() {
				p.P("for item in ", id, ".values {")
				p.Indent()
				nested("item")
				p.Dedent()
				p.P("}")
			})
		}
		return out
	case onkir.KindScalar:
	default:
		return out
	}
	if !hasScalarRules(f) {
		return out
	}
	add(func() {
		value := id
		if isNullableKind(f) {
			value = "value"
			p.P("if let value = ", id, " {")
			p.Indent()
		}
		writeScalarRules(p, f, value)
		if isNullableKind(f) {
			p.Dedent()
			p.P("}")
		}
	})
	return out
}

func hasScalarRules(f *onkir.Field) bool {
	switch {
	case f.Type.Scalar == onkir.ScalarString:
		for _, name := range []string{"email", "uuid", "uri", "pattern", "len", "in"} {
			if f.HasDecorator(name) {
				return true
			}
		}
		return false
	case isNumeric(f.Type.Scalar):
		for _, name := range []string{"in", "range", "gt", "gte", "lt", "lte"} {
			if f.HasDecorator(name) {
				return true
			}
		}
	}
	return false
}

func writeScalarRules(p *Printer, f *onkir.Field, v string) {
	add := func(cond, msg string) {
		p.P("if ", cond, " { violations.append(", swiftString(msg), ") }")
	}
	if f.Type.Scalar == onkir.ScalarString {
		if f.HasDecorator("email") {
			add("!"+v+".isEmpty && !onekitMatches(onekitEmailPattern, "+v+")", f.Name+" must be a valid email")
		}
		if f.HasDecorator("uuid") {
			add("!"+v+".isEmpty && !onekitMatches(onekitUUIDPattern, "+v+")", f.Name+" must be a valid UUID")
		}
		if f.HasDecorator("uri") {
			add("!"+v+".isEmpty && !onekitMatches(onekitURIPattern, "+v+")", f.Name+" must be a valid URI")
		}
		if d, ok := f.Decorator("pattern"); ok {
			pattern, _ := d.Value()
			add("!"+v+".isEmpty && !onekitMatches("+swiftString(pattern)+", "+v+")", f.Name+" has invalid format")
		}
		if d, ok := f.Decorator("len"); ok && len(d.Args) == 2 {
			add(v+".unicodeScalars.count < "+d.Args[0].Value+" || "+v+".unicodeScalars.count > "+d.Args[1].Value, f.Name+" has invalid length")
		}
		if d, ok := f.Decorator("in"); ok {
			values := make([]string, 0, len(d.Args))
			for _, arg := range d.Args {
				values = append(values, swiftString(arg.Value))
			}
			add("!["+strings.Join(values, ", ")+"].contains("+v+")", f.Name+" must be one of the allowed values")
		}
		return
	}
	if !isNumeric(f.Type.Scalar) {
		return
	}
	if d, ok := f.Decorator("in"); ok {
		values := make([]string, 0, len(d.Args))
		for _, arg := range d.Args {
			values = append(values, arg.Value)
		}
		add("!["+strings.Join(values, ", ")+"].contains("+v+")", f.Name+" must be one of the allowed values")
	}
	if d, ok := f.Decorator("range"); ok && len(d.Args) == 2 {
		add(v+" < "+d.Args[0].Value+" || "+v+" > "+d.Args[1].Value, f.Name+" violates @range")
	}
	for _, rule := range []struct{ name, op string }{{"gt", "<="}, {"gte", "<"}, {"lt", ">="}, {"lte", ">"}} {
		if d, ok := f.Decorator(rule.name); ok {
			value, _ := d.Value()
			add(v+" "+rule.op+" "+value, f.Name+" violates @"+rule.name)
		}
	}
}

func isNumeric(kind onkir.ScalarKind) bool {
	switch kind {
	case onkir.ScalarInt32, onkir.ScalarInt64, onkir.ScalarUint32, onkir.ScalarUint64, onkir.ScalarFloat32, onkir.ScalarFloat64:
		return true
	}
	return false
}
