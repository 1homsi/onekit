package gents

import (
	"fmt"
	"regexp"
	"strconv"
	"strings"
)

var sharedRuntimeValues = []string{
	"ApiError", "TypedApiError", "RequestValidationError", "DEFAULT_REQUEST_TIMEOUT_MS",
	"DEFAULT_MAX_RESPONSE_BODY_BYTES", "DEFAULT_MAX_SSE_LINE_BYTES",
	"responseBodyLimit", "readResponseText", "requestSignal",
}

var sharedRuntimeTypes = []string{"RequestOptions", "ApiErrorParser", "ApiErrorDetails"}

var sharedRuntimeReexportedValues = []string{"ApiError", "TypedApiError", "RequestValidationError", "DEFAULT_REQUEST_TIMEOUT_MS"}

// writeSharedRuntimeImports makes a client import the runtime pieces from the
// shared module and re-export the public ones, so code that imports ApiError
// from a client module keeps working and gets the one shared class.
func writeSharedRuntimeImports(p *Printer, specifier string) {
	quoted := strconv.Quote(specifier)
	p.P(fmt.Sprintf("import { %s } from %s;", strings.Join(sharedRuntimeValues, ", "), quoted))
	p.P(fmt.Sprintf("import type { %s } from %s;", strings.Join(sharedRuntimeTypes, ", "), quoted))
	p.P(fmt.Sprintf("export { %s } from %s;", strings.Join(sharedRuntimeReexportedValues, ", "), quoted))
	p.P(fmt.Sprintf("export type { %s } from %s;", strings.Join(sharedRuntimeTypes, ", "), quoted))
}

var privateRuntimeHelper = regexp.MustCompile(`(?m)^(async function |function |const )(DEFAULT_MAX_RESPONSE_BODY_BYTES|DEFAULT_MAX_SSE_LINE_BYTES|responseBodyLimit|readResponseText|requestSignal)\b`)

// GenerateClientRuntime generates the shared client runtime module: the error
// classes, request options and the response-size, timeout and SSE helpers
// that every generated client would otherwise declare for itself.
func GenerateClientRuntime() []byte {
	p := newPrinterWithOptions(nil, Options{})
	p.P("// Code generated by onek. DO NOT EDIT.")
	p.P()
	writeResponseBodyRuntime(p)
	writeAPIError(p)
	writeTypedAPIError(p)
	return privateRuntimeHelper.ReplaceAll(p.Bytes(), []byte("export $1$2"))
}
