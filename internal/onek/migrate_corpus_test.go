// TestMigrateCorpus converts every corpus schema to TypeSpec and requires the
// TypeSpec project to generate exactly what the .onk project generates, for
// every target. $ONK_CORPUS adds a directory of .onk schemas to check.
func TestMigrateCorpus(t *testing.T) {
	t.Parallel()
	if testing.Short() {
		t.Skip("builds every corpus schema twice")
	}
	repoNodeModules(t)
	// The .onk side of each comparison is built as it was before TypeSpec.
	onkSchemasAccepted.Store(true)
	t.Cleanup(func() { onkSchemasAccepted.Store(false) })
	corpus := map[string]string{}
	for name, source := range migrateCorpus {
		corpus[name] = source
	}
	if dir := os.Getenv("ONK_CORPUS"); dir != "" {
		files, err := filepath.Glob(filepath.Join(dir, "*.onk"))
		if err != nil {
			t.Fatal(err)
		}
		for _, file := range files {
			source, err := os.ReadFile(file)
			if err != nil {
				t.Fatal(err)
			}
			corpus[strings.TrimSuffix(filepath.Base(file), ".onk")] = string(source)
		}
	}
	for name, source := range corpus {
		t.Run(name, func(t *testing.T) {
			t.Parallel()
			checkMigration(t, map[string]string{"schema.onk": source}, false)
		})
	}
}

// checkMigration builds a .onk project and the TypeSpec onkt migrate writes
// for it, and requires the same generated files. A project that does not
// build as .onk is skipped unless it must build.
func checkMigration(t *testing.T, files map[string]string, mustBuild bool) {
	t.Helper()
	var sources []string
	for _, name := range slices.Sorted(maps.Keys(files)) {
		sources = append(sources, "// "+name+"\n"+files[name])
	}
	source := strings.Join(sources, "\n")
	base := t.TempDir()
	onkDir := filepath.Join(base, "onk")
	var config string
	for _, candidate := range []string{corpusAllTargets, corpusWebTargets} {
		writeCorpusProject(t, onkDir, candidate, files)
		if err := Build(onkDir); err == nil {
			config = candidate
			break
		}
		os.RemoveAll(onkDir)
	}
	if config == "" {
		if mustBuild {
			writeCorpusProject(t, onkDir, corpusWebTargets, files)
			t.Fatalf("the .onk schema does not build: %v", Build(onkDir))
		}
		t.Skip("the .onk schema does not build")
	}

	tspDir := filepath.Join(base, "tsp")
	writeCorpusProject(t, tspDir, config, files)
	if _, err := Migrate(tspDir, MigrateOptions{}); err != nil {
		t.Fatalf("migrate: %v", err)
	}
	linkTypeSpec(t, tspDir)
	if err := Build(tspDir); err != nil {
		t.Fatalf("build the migrated project: %v\n--- schema ---\n%s\n--- typespec ---\n%s", err, source, readTSP(t, tspDir))
	}
	want := generatedFiles(t, filepath.Join(onkDir, "gen"))
	got := generatedFiles(t, filepath.Join(tspDir, "gen"))
	var diffs []string
	for path, content := range want {
		if !bytes.Equal(got[path], content) {
			diffs = append(diffs, path)
		}
	}
	for path := range got {
		if _, ok := want[path]; !ok {
			diffs = append(diffs, path+" (extra)")
		}
	}
	sort.Strings(diffs)
	if len(diffs) > 0 {
		t.Errorf("generated files differ: %s\n--- schema ---\n%s\n--- typespec ---\n%s", strings.Join(diffs, ", "), source, readTSP(t, tspDir))
		if dump := os.Getenv("ONK_CORPUS_DUMP"); dump != "" {
			name := filepath.Base(t.Name())
			for _, path := range diffs {
				path = strings.TrimSuffix(path, " (extra)")
				_ = os.MkdirAll(filepath.Join(dump, name, filepath.Dir(path)), 0o755)
				_ = os.WriteFile(filepath.Join(dump, name, path+".want"), want[path], 0o644)
				_ = os.WriteFile(filepath.Join(dump, name, path+".got"), got[path], 0o644)
			}
		}
	}
}

func writeCorpusProject(t *testing.T, dir, config string, files map[string]string) {
	t.Helper()
	if err := os.MkdirAll(dir, 0o755); err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(filepath.Join(dir, configFileName), []byte(config), 0o644); err != nil {
		t.Fatal(err)
	}
	for name, source := range files {
		if err := os.WriteFile(filepath.Join(dir, name), []byte(source), 0o644); err != nil {
			t.Fatal(err)
		}
	}
}

func readTSP(t *testing.T, dir string) string {
	t.Helper()
	var b strings.Builder
	paths, _ := filepath.Glob(filepath.Join(dir, "*.tsp"))
	for _, path := range paths {
		data, _ := os.ReadFile(path)
		b.WriteString("// " + filepath.Base(path) + "\n")
		b.Write(data)
	}
	return b.String()
}

func generatedFiles(t *testing.T, dir string) map[string][]byte {
	t.Helper()
	files := map[string][]byte{}
	_ = filepath.WalkDir(dir, func(path string, d fs.DirEntry, err error) error {
		if err != nil || d.IsDir() {
			return err
		}
		data, err := os.ReadFile(path)
		if err != nil {
			return err
		}
		rel, _ := filepath.Rel(dir, path)
		files[filepath.ToSlash(rel)] = data
		return nil
	})
	return files
}

// .onk let a service share its name with a message or enum of its package;
// TypeSpec does not, so the interface is renamed and keeps generating under
// the service's name.
func TestMigrateRenamesAnInterfaceThatSharesAName(t *testing.T) {
	t.Parallel()
	repoNodeModules(t)
	onkSchemasAccepted.Store(true)
	t.Cleanup(func() { onkSchemasAccepted.Store(false) })
	checkMigration(t, map[string]string{
		"branding.onk": `package app
message PublicBranding { name: string }
message GetBrandingRequest { slug: string }
service PublicBranding { get(GetBrandingRequest) -> PublicBranding @get("/branding/{slug}") }
`,
		"twofactor.onk": `package app
message MyTwoFactor { enabled: bool }
message MyTwoFactorService { note: string }
message Empty {}
service MyTwoFactor { status(Empty) -> MyTwoFactor @get("/2fa") }
`,
		"query.onk": `package app
enum QueryScope { ALL MINE }
message Query { scope: QueryScope }
`,
		"scope.onk": `package app
service QueryScope { run(Query) -> Query @post("/query") }
`,
	}, true)
}

// Under int64_encoding = "number" every 64-bit integer is a JSON number, so
// the migrated schema must not say @encode(string) on any of them.
func TestMigrateUnderInt64NumberWritesNoStringEncodings(t *testing.T) {
	t.Parallel()
	repoNodeModules(t)
	onkSchemasAccepted.Store(true)
	t.Cleanup(func() { onkSchemasAccepted.Store(false) })
	config := "int64_encoding = \"number\"\n" + corpusAllTargets
	files := map[string]string{"schema.onk": `package app
message CurrentUser {
  id: int64
  org_ids: int64[]
  big: uint64
  pick: oneof { n: int64  s: string }
}
message Lookup { id: int64 }
service Users { me(Lookup) -> CurrentUser @get("/me/{id}") }
`}
	base := t.TempDir()
	onkDir, tspDir := filepath.Join(base, "onk"), filepath.Join(base, "tsp")
	writeCorpusProject(t, onkDir, config, files)
	if err := Build(onkDir); err != nil {
		t.Fatalf("build the .onk project: %v", err)
	}
	writeCorpusProject(t, tspDir, config, files)
	if _, err := Migrate(tspDir, MigrateOptions{}); err != nil {
		t.Fatalf("migrate: %v", err)
	}
	if tsp := readTSP(t, tspDir); strings.Contains(tsp, `encode(string)`) || strings.Contains(tsp, `encode("string")`) {
		t.Fatalf("a string encoding contradicts int64_encoding = \"number\":\n%s", tsp)
	}
	linkTypeSpec(t, tspDir)
	if err := Build(tspDir); err != nil {
		t.Fatalf("build the migrated project: %v\n%s", err, readTSP(t, tspDir))
	}
	want, got := generatedFiles(t, filepath.Join(onkDir, "gen")), generatedFiles(t, filepath.Join(tspDir, "gen"))
	if len(want) == 0 || len(want) != len(got) {
		t.Fatalf("generated %d files from .onk and %d from TypeSpec", len(want), len(got))
	}
	for path, content := range want {
		if !bytes.Equal(got[path], content) {
			t.Errorf("%s differs", path)
		}
	}
}
