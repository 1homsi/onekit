package gengo

import (
	"fmt"
	"strings"

	"github.com/1homsi/onekit/internal/onkir"
)

func methodNeedsStrconv(m *onkir.Method) bool {
	for _, field := range m.Request.Fields {
		if _, ok := field.Decorator("query"); !ok || field.Type == nil || field.Type.Kind != onkir.KindScalar {
			continue
		}
		if field.Type.Scalar != onkir.ScalarString {
			return true
		}
	}
	return false
}

type clientImports struct {
	base64, bytes, hex, url, strconv, strings, bufio bool
}

func clientImportsNeeded(file *onkir.File) clientImports {
	var imp clientImports
	for _, s := range file.Services {
		for _, m := range s.Methods {
			verb, _ := m.Verb()
			path, _ := m.Path()
			imp.url = imp.url || len(pathParamNames(path)) > 0
			switch {
			case m.IsStream():
				imp.url = true
				imp.strconv = imp.strconv || methodNeedsStrconv(m)
				imp.bufio = true
				imp.strings = true
			case isBodyBearingVerb(verb):
				imp.bytes = true
				if bodyField, ok := m.BodyField(); ok {
					if field := findField(m.Request, bodyField); field != nil {
						imp.strconv = imp.strconv || needsInt64StringEncoding(field)
						switch bytesEncodingValue(field) {
						case bytesEncodeHex:
							imp.hex = true
						case bytesEncodeBase64Raw, bytesEncodeBase64URL, bytesEncodeBase64URLRaw:
							imp.base64 = true
						}
					}
				}
			default:
				imp.url = true
				imp.strconv = imp.strconv || methodNeedsStrconv(m)
			}
			imp.strings = imp.strings || len(pathParamNames(path)) > 0
		}
	}
	return imp
}

// GenerateClient generates client.gen.go treating every message/enum type as
// local. Use GenerateClientWithResolver for a multi-package project where
// some referenced types live in a different generated package.
func GenerateClient(file *onkir.File) ([]byte, error) {
	return GenerateClientWithResolver(file, nil)
}

func GenerateClientWithResolver(file *onkir.File, resolver PackageResolver) ([]byte, error) {
	if len(file.Services) == 0 {
		return nil, nil
	}

	imp := clientImportsNeeded(file)
	hasStream := fileHasStreamMethods(file)
	externalRefs := collectServiceExternalRefs(file, resolver)

	p := newPrinter(resolver)
	p.P("// Code generated by onek. DO NOT EDIT.")
	p.P("package ", GoPackageName(file))
	p.P()
	p.P("import (")
	if imp.bufio {
		p.P(`"bufio"`)
	}
	if imp.base64 {
		p.P(`"encoding/base64"`)
	}
	if imp.bytes {
		p.P(`"bytes"`)
	}
	p.P(`"context"`)
	p.P(`"encoding/json"`)
	p.P(`"fmt"`)
	if imp.hex {
		p.P(`"encoding/hex"`)
	}
	p.P(`"io"`)
	p.P(`"net/http"`)
	if imp.url {
		p.P(`"net/url"`)
	}
	if imp.strconv {
		p.P(`"strconv"`)
	}
	if imp.strings {
		p.P(`"strings"`)
	}
	for _, ref := range externalRefs {
		p.P(ref.Alias, " ", fmt.Sprintf("%q", ref.ImportPath))
	}
	p.P(")")
	p.P()

	if hasStream {
		writeEventStreamRuntime(p)
	}
	writeResponseBodyRuntime(p)

	for _, s := range file.Services {
		writeClientType(p, s)
		for _, m := range s.Methods {
			if m.IsStream() {
				writeSSEClientMethod(p, s, m)
			} else {
				writeClientMethod(p, s, m)
			}
		}
	}

	return p.Format()
}

func writeClientType(p *Printer, s *onkir.Service) {
	p.P("type ", s.Name, "Client struct {")
	p.P("BaseURL string")
	p.P("HTTPClient *http.Client")
	p.P("Headers map[string]string")
	p.P("MaxResponseBodyBytes int64")
	p.P("MaxSSELineBytes int")
	p.P("}")
	p.P()
	p.P("func New", s.Name, "Client(baseURL string) *", s.Name, "Client {")
	p.P("return &", s.Name, "Client{BaseURL: baseURL, HTTPClient: http.DefaultClient, Headers: map[string]string{}, MaxResponseBodyBytes: defaultMaxResponseBodyBytes, MaxSSELineBytes: defaultMaxSSELineBytes}")
	p.P("}")
	p.P()
}

func writeClientMethod(p *Printer, s *onkir.Service, m *onkir.Method) {
	verb, _ := m.Verb()
	path, _ := m.Path()
	fullPath := s.BasePath + path
	bodyBearing := isBodyBearingVerb(verb)

	p.P("func (c *", s.Name, "Client) ", PascalCase(m.Name),
		"(ctx context.Context, req *", p.MessageTypeName(m.Request), ") (*",
		p.MessageTypeName(m.Response), ", error) {")
	p.P(`if validator, ok := any(req).(interface{ Validate() error }); ok { if err := validator.Validate(); err != nil { return nil, fmt.Errorf("validate request: %w", err) } }`)

	p.P("path := ", fmt.Sprintf("%q", fullPath))
	for _, paramName := range pathParamNames(path) {
		field := findField(m.Request, paramName)
		if field == nil {
			continue
		}
		p.P("path = strings.ReplaceAll(path, ", fmt.Sprintf("%q", "{"+paramName+"}"), ", ",
			fmt.Sprintf("url.PathEscape(fmt.Sprintf(%q, req.%s))", "%v", PascalCase(paramName)), ")")
	}

	if bodyBearing {
		bodyExpr := "req"
		if bodyField, ok := m.BodyField(); ok {
			if field := findField(m.Request, bodyField); field != nil {
				if bodyFieldNeedsCustomJSON(field) {
					writeBodyValue(p, field)
					p.P("body, err := json.Marshal(bodyValue)")
				} else {
					bodyExpr = "req." + PascalCase(field.Name)
					p.P("body, err := json.Marshal(", bodyExpr, ")")
				}
			} else {
				p.P("body, err := json.Marshal(", bodyExpr, ")")
			}
		} else {
			p.P("body, err := json.Marshal(", bodyExpr, ")")
		}
		p.P("if err != nil {")
		p.P(`return nil, fmt.Errorf("marshal request: %w", err)`)
		p.P("}")
	} else {
		writeClientQueryParams(p, m.Request)
	}

	p.P(
		"httpReq, err := http.NewRequestWithContext(ctx, ",
		fmt.Sprintf("%q", strings.ToUpper(verb)), ", c.BaseURL+path, ",
		bodyReaderExpr(bodyBearing), ")",
	)
	p.P("if err != nil {")
	p.P(`return nil, fmt.Errorf("build request: %w", err)`)
	p.P("}")
	if bodyBearing {
		p.P(`httpReq.Header.Set("Content-Type", "application/json")`)
	}
	p.P("for k, v := range c.Headers {")
	p.P("httpReq.Header.Set(k, v)")
	p.P("}")

	p.P("resp, err := c.HTTPClient.Do(httpReq)")
	p.P("if err != nil {")
	p.P(`return nil, fmt.Errorf("do request: %w", err)`)
	p.P("}")
	p.P("defer resp.Body.Close()")
	p.P()

	writeClientErrorHandling(p, m)

	p.P("result := new(", p.MessageTypeName(m.Response), ")")
	p.P("if err := json.NewDecoder(io.LimitReader(resp.Body, responseBodyLimit(c.MaxResponseBodyBytes))).Decode(result); err != nil {")
	p.P(`return nil, fmt.Errorf("decode response: %w", err)`)
	p.P("}")
	p.P("return result, nil")
	p.P("}")
	p.P()
}

func writeResponseBodyRuntime(p *Printer) {
	p.P("const defaultMaxResponseBodyBytes int64 = 8 << 20")
	p.P("const defaultMaxSSELineBytes = 1 << 20")
	p.P()
	p.P("func responseBodyLimit(value int64) int64 {")
	p.P("if value <= 0 { return defaultMaxResponseBodyBytes }")
	p.P("return value")
	p.P("}")
	p.P()
	p.P("func readResponseBody(body io.Reader, limit int64) ([]byte, error) {")
	p.P("limit = responseBodyLimit(limit)")
	p.P("data, err := io.ReadAll(io.LimitReader(body, limit+1))")
	p.P("if err != nil { return nil, err }")
	p.P("if int64(len(data)) > limit { return nil, fmt.Errorf(\"response body exceeds configured limit\") }")
	p.P("return data, nil")
	p.P("}")
	p.P()
}

func bodyFieldNeedsCustomJSON(field *onkir.Field) bool {
	return needsInt64StringEncoding(field) || needsEnumNumberEncoding(field) ||
		bytesEncodingValue(field) != "" || timestampEncodingValue(field) != ""
}

func writeBodyValue(p *Printer, field *onkir.Field) {
	fieldExpr := "req." + PascalCase(field.Name)
	p.P("var bodyValue any")
	if field.Optional {
		p.P("if ", fieldExpr, " == nil {")
		p.P("bodyValue = nil")
		p.P("} else {")
		p.P("bodyValue = ", bodyWireValueExpr(field, "*"+fieldExpr))
		p.P("}")
		return
	}
	p.P("bodyValue = ", bodyWireValueExpr(field, fieldExpr))
}

func bodyWireValueExpr(field *onkir.Field, expr string) string {
	switch {
	case needsInt64StringEncoding(field):
		return int64FormatCall(field.Type.Scalar, expr)
	case needsEnumNumberEncoding(field):
		return "int32(" + expr + ")"
	case bytesEncodingValue(field) != "":
		return bytesEncodeCall(bytesEncodingValue(field), expr)
	case timestampEncodingValue(field) != "":
		return timestampEncodeExpr(timestampEncodingValue(field), expr)
	default:
		return expr
	}
}

func bodyReaderExpr(bodyBearing bool) string {
	if bodyBearing {
		return "bytes.NewReader(body)"
	}
	return "nil"
}

func writeClientQueryParams(p *Printer, req *onkir.Message) {
	p.P("query := url.Values{}")
	for _, field := range req.Fields {
		d, ok := field.Decorator("query")
		if !ok || field.Type == nil || field.Type.Kind != onkir.KindScalar {
			continue
		}
		queryName, _ := d.Value()
		if queryName == "" {
			queryName = field.Name
		}
		fieldExpr := "req." + PascalCase(field.Name)
		if field.Repeated {
			p.P("for _, value := range ", fieldExpr, " {")
			p.P("query.Add(", fmt.Sprintf("%q", queryName), ", ", clientStringifyExpr(field.Type.Scalar, "value"), ")")
			p.P("}")
			continue
		}
		if field.Optional {
			p.P("if ", fieldExpr, " != nil {")
			p.P(
				"query.Set(",
				fmt.Sprintf("%q", queryName),
				", ",
				clientStringifyExpr(field.Type.Scalar, "*"+fieldExpr),
				")",
			)
			p.P("}")
			continue
		}
		p.P("query.Set(", fmt.Sprintf("%q", queryName), ", ", clientStringifyExpr(field.Type.Scalar, fieldExpr), ")")
	}
	p.P("if len(query) > 0 {")
	p.P(`path += "?" + query.Encode()`)
	p.P("}")
}

func clientStringifyExpr(kind onkir.ScalarKind, expr string) string {
	switch kind {
	case onkir.ScalarString:
		return expr
	case onkir.ScalarBool:
		return fmt.Sprintf("strconv.FormatBool(%s)", expr)
	case onkir.ScalarInt32, onkir.ScalarInt64:
		return fmt.Sprintf("strconv.FormatInt(int64(%s), 10)", expr)
	case onkir.ScalarUint32, onkir.ScalarUint64:
		return fmt.Sprintf("strconv.FormatUint(uint64(%s), 10)", expr)
	case onkir.ScalarFloat32, onkir.ScalarFloat64:
		return fmt.Sprintf("strconv.FormatFloat(float64(%s), 'f', -1, 64)", expr)
	case onkir.ScalarBytes, onkir.ScalarTimestamp:
		return fmt.Sprintf("fmt.Sprintf(%q, %s)", "%v", expr)
	default:
		return fmt.Sprintf("fmt.Sprintf(%q, %s)", "%v", expr)
	}
}

func writeClientErrorHandling(p *Printer, m *onkir.Method) {
	p.P("if resp.StatusCode < 200 || resp.StatusCode >= 300 {")
	p.P("respBody, bodyErr := readResponseBody(resp.Body, c.MaxResponseBodyBytes)")
	p.P("if bodyErr != nil { return nil, bodyErr }")
	for _, errType := range m.ErrorTypes {
		status := 500
		if code, ok := errType.StatusCode(); ok {
			status = code
		}
		p.P(fmt.Sprintf("if resp.StatusCode == %d {", status))
		p.P("e := new(", p.MessageTypeName(errType), ")")
		p.P("if jsonErr := json.Unmarshal(respBody, e); jsonErr == nil {")
		p.P("return nil, e")
		p.P("}")
		p.P("}")
	}
	p.P(`return nil, fmt.Errorf("unexpected status %d: %s", resp.StatusCode, string(respBody))`)
	p.P("}")
}
