// SharedRuntime points generated packages at one runtime package that holds
// the server core, instead of every package carrying its own copy. Types such
// as ServerError and ErrorWriter then mean the same thing in every package, so
// one error writer, authorizer, middleware or option list works for all of them.
type SharedRuntime struct {
	// ImportPath is the import path of the shared package.
	ImportPath string
	// Package is the shared package's name.
	Package string
}

var sharedRuntimeTypes = []string{
	"RequestMetadata", "ScopeError", "Middleware", "RequestIDGenerator", "Authorizer",
	"RequestResult", "RequestObserver", "ServerOption", "ServerOptions", "ServerError",
	"ErrorWriter", "ResponseControl",
}

var sharedRuntimeFuncs = []string{
	"RequestMetadataFromContext", "SetResponseStatus", "ResponseHeader", "HTTPRequestFromContext",
	"RequestIDFromContext", "HTTPRequestContext", "RouteContext", "Mount", "NotModified", "Redirect", "SetCookie", "WithMux", "WithMiddleware",
	"WithRequestID", "WithRequestIDGenerator", "WithAuthorizer", "WithScopes", "WithErrorWriter",
	"ErrorHandler", "WithRequestObserver", "WithMaxRequestBodyBytes", "WithSSEHeartbeat",
}

var sharedRuntimeWSFuncs = []string{
	"WithMaxWSFrameBytes", "WithWSPingInterval", "WithMaxWSMessageBytes", "WithWSAcceptOptions",
}

func writeSharedRuntimeAliases(p *Printer, hasWS bool, shared *SharedRuntime) {
	p.P("// The server core lives in ", shared.ImportPath, "; these aliases keep this")
	p.P("// package's API the same while sharing one set of types with every other package.")
	p.P("type (")
	for _, name := range sharedRuntimeTypes {
		p.P(name, " = ", shared.Package, ".", name)
	}
	p.P(")")
	p.P()
	funcs := sharedRuntimeFuncs
	if hasWS {
		funcs = append(append([]string{}, funcs...), sharedRuntimeWSFuncs...)
	}
	p.P("var (")
	for _, name := range funcs {
		p.P(name, " = ", shared.Package, ".", name)
	}
	p.P(")")
	p.P()
}

// GenerateServerRuntime generates the shared runtime package. hasWS says
// whether any package that uses it declares WebSocket methods.
func GenerateServerRuntime(packageName string, hasWS bool, contentType string) ([]byte, error) {
	p := newPrinter(nil)
	p.P("// Code generated by onek. DO NOT EDIT.")
	p.P("package ", packageName)
	p.P()
	p.P("import (")
	for _, imp := range []string{"bytes", "context", "crypto/rand", "encoding/hex", "encoding/json", "errors", "net/http", "strings", "sync", "time"} {
		p.P(strconv.Quote(imp))
	}
	if hasWS {
		p.P(strconv.Quote("github.com/coder/websocket"))
	}
	p.P(")")
	p.P()
	writeJSONFunc(p, contentType)
	p.P()
	p.P(`func writeJSONError(w http.ResponseWriter, status int, message string) {`)
	p.P(`w.Header().Set("Content-Type", `, jsonContentTypeLiteral(contentType), `)`)
	p.P(`w.WriteHeader(status)`)
	p.P(`_ = json.NewEncoder(w).Encode(map[string]string{"message": message})`)
	p.P(`}`)
	p.P()
	writeServerCore(p, hasWS)
	out, err := p.Format()
	if err != nil {
		return nil, err
	}
	return pruneUnusedImports(out)
}

// pruneUnusedImports drops import specs whose package name is never used in
// the file, so one emitter can serve packages with different needs.
func pruneUnusedImports(src []byte) ([]byte, error) {
	fset := token.NewFileSet()
	file, err := parser.ParseFile(fset, "", src, parser.ParseComments)
	if err != nil {
		return nil, fmt.Errorf("parse generated source: %w", err)
	}
	used := map[string]bool{}
	ast.Inspect(file, func(n ast.Node) bool {
		if sel, ok := n.(*ast.SelectorExpr); ok {
			if id, ok := sel.X.(*ast.Ident); ok {
				used[id.Name] = true
			}
		}
		return true
	})
	var unused []string
	for _, spec := range file.Imports {
		path, err := strconv.Unquote(spec.Path.Value)
		if err != nil {
			continue
		}
		name := path[strings.LastIndex(path, "/")+1:]
		if spec.Name != nil {
			name = spec.Name.Name
		}
		if name == "_" || name == "." || used[name] {
			continue
		}
		unused = append(unused, spec.Path.Value)
	}
	if len(unused) == 0 {
		return src, nil
	}
	lines := strings.Split(string(src), "\n")
	kept := make([]string, 0, len(lines))
	inImports := false
	for _, line := range lines {
		trimmed := strings.TrimSpace(line)
		switch {
		case strings.HasPrefix(trimmed, "import ("):
			inImports = true
		case inImports && trimmed == ")":
			inImports = false
		case inImports:
			if slices.ContainsFunc(unused, func(quoted string) bool { return strings.HasSuffix(trimmed, quoted) }) {
				continue
			}
		}
		kept = append(kept, line)
	}
	return format.Source([]byte(strings.Join(kept, "\n")))
}
