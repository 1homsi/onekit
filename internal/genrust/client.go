package genrust

import (
	"strconv"
	"strings"

	"github.com/1homsi/onekit/internal/onkir"
)

func GenerateClient(file *onkir.File) []byte {
	return GenerateClientWithResolver(file, nil)
}

func GenerateClientWithResolver(file *onkir.File, resolver PackageResolver) []byte {
	if len(file.Services) == 0 {
		return nil
	}
	p := newPrinter(resolver)
	p.P("// Code generated by onek. DO NOT EDIT.")
	p.Blank()
	p.P("use super::types::*;")
	if onkir.FileHasStreamMethods(file) {
		p.P("use futures_util::{Stream, StreamExt as _};")
	}
	if fileNeedsBodyWireEncoding(file) {
		p.P("use base64::Engine as _;")
	}
	p.P("use serde::Serialize;")
	p.Blank()
	writeClientHelpers(p)
	for _, service := range file.Services {
		writeClient(p, service)
	}
	return p.Bytes()
}

func writeClientHelpers(p *Printer) {
	p.P("const DEFAULT_MAX_RESPONSE_BODY_BYTES: usize = 8 * 1024 * 1024;")
	p.P("const DEFAULT_MAX_SSE_FRAME_BYTES: usize = 1024 * 1024;")
	p.Blank()
	p.P("async fn read_response_body(mut response: reqwest::Response, limit: usize) -> Result<Vec<u8>, String> {")
	p.Indent()
	p.P("let limit = if limit == 0 { DEFAULT_MAX_RESPONSE_BODY_BYTES } else { limit };")
	p.P("let mut body = Vec::new();")
	p.P("while let Some(chunk) = response.chunk().await.map_err(|error| error.to_string())? {")
	p.Indent()
	p.P("if body.len().saturating_add(chunk.len()) > limit { return Err(\"response body exceeds configured limit\".into()); }")
	p.P("body.extend_from_slice(&chunk);")
	p.Dedent()
	p.P("}")
	p.P("Ok(body)")
	p.Dedent()
	p.P("}")
	p.Blank()
	p.P("#[allow(dead_code)]")
	p.P("fn query_value<T: Serialize>(value: &T) -> String {")
	p.Indent()
	p.P("match serde_json::to_value(value).expect(\"generated request value must serialize\") {")
	p.Indent()
	p.P("serde_json::Value::String(value) => value,")
	p.P("serde_json::Value::Null => String::new(),")
	p.P("value => value.to_string(),")
	p.Dedent()
	p.P("}")
	p.Dedent()
	p.P("}")
	p.Blank()
}

func writeClient(p *Printer, service *onkir.Service) {
	name := PascalCase(service.Name)
	p.P("#[derive(Debug, Clone)]")
	p.P("pub struct ", name, "Client {")
	p.Indent()
	p.P("base_url: String,")
	p.P("http: reqwest::Client,")
	p.P("headers: reqwest::header::HeaderMap,")
	p.P("max_response_body_bytes: usize,")
	p.P("max_sse_frame_bytes: usize,")
	p.Dedent()
	p.P("}")
	p.Blank()
	p.P("impl ", name, "Client {")
	p.Indent()
	p.P("pub fn new(base_url: impl Into<String>) -> Self {")
	p.Indent()
	p.P(
		"Self { base_url: base_url.into().trim_end_matches('/').to_owned(), ",
		"http: reqwest::Client::new(), headers: reqwest::header::HeaderMap::new(), ",
		"max_response_body_bytes: DEFAULT_MAX_RESPONSE_BODY_BYTES, max_sse_frame_bytes: DEFAULT_MAX_SSE_FRAME_BYTES }",
	)
	p.Dedent()
	p.P("}")
	p.Blank()
	p.P("pub fn with_http_client(mut self, http: reqwest::Client) -> Self {")
	p.Indent()
	p.P("self.http = http;")
	p.P("self")
	p.Dedent()
	p.P("}")
	p.Blank()
	p.P(
		"pub fn with_header(mut self, name: reqwest::header::HeaderName, ",
		"value: reqwest::header::HeaderValue) -> Self {",
	)
	p.Indent()
	p.P("self.headers.insert(name, value);")
	p.P("self")
	p.Dedent()
	p.P("}")
	p.Blank()
	p.P("pub fn with_max_response_body_bytes(mut self, limit: usize) -> Self {")
	p.Indent()
	p.P("self.max_response_body_bytes = if limit == 0 { DEFAULT_MAX_RESPONSE_BODY_BYTES } else { limit };")
	p.P("self")
	p.Dedent()
	p.P("}")
	p.Blank()
	p.P("pub fn with_max_sse_frame_bytes(mut self, limit: usize) -> Self {")
	p.Indent()
	p.P("self.max_sse_frame_bytes = if limit == 0 { DEFAULT_MAX_SSE_FRAME_BYTES } else { limit };")
	p.P("self")
	p.Dedent()
	p.P("}")
	p.Blank()
	var wsMethods []*onkir.Method
	for _, method := range service.Methods {
		if method.IsWebSocket() {
			wsMethods = append(wsMethods, method)
			writeRustWSClientMethod(p, service, method)
			continue
		}
		writeClientMethod(p, service, method)
	}
	writeRustWSDuplexTypes(p, service, wsMethods)
	p.Dedent()
	p.P("}")
	p.Blank()
	for _, method := range service.Methods {
		writeClientError(p, service, method)
	}
}

//nolint:nestif // HTTP binding branches mirror schema body/query/path combinations.
func writeClientMethod(
	p *Printer,
	service *onkir.Service,
	method *onkir.Method,
) {
	methodName := RustIdent(method.Name)
	errorName := clientErrorName(service, method)
	requestType := p.MessageTypeName(method.Request)
	responseType := p.MessageTypeName(method.Response)
	verb, _ := method.Verb()
	path, _ := method.Path()
	fullPath := service.BasePath + path

	if method.IsStream() {
		p.P(
			"pub async fn ", methodName, "(&self, req: &", requestType,
			") -> Result<impl Stream<Item = Result<", responseType, ", ", errorName,
			">>, ", errorName, "> {",
		)
	} else {
		p.P(
			"pub async fn ", methodName, "(&self, req: &", requestType,
			") -> Result<", responseType, ", ", errorName, "> {",
		)
	}
	p.Indent()
	p.P("req.validate().map_err(", errorName, "::Validation)?;")
	p.P("let mut path = ", strconv.Quote(fullPath), ".to_owned();")
	pathFields := pathFieldNames(path)
	for _, name := range pathFields {
		if field := onkir.FindField(method.Request, name); field != nil {
			access := "req." + RustIdent(field.Name)
			value := "&" + access
			if field.Optional {
				p.P(
					"let path_value = ", access, ".as_ref().ok_or_else(|| ", errorName,
					"::InvalidRequest(", strconv.Quote("missing path field "+field.Name),
					".into()))?;",
				)
				value = "path_value"
			}
			p.P(
				"path = path.replace(", strconv.Quote("{"+name+"}"),
				", &urlencoding::encode(&query_value(", value, ")));",
			)
		}
	}
	p.P("let url = format!(\"{}{}\", self.base_url, path);")
	if verb == queryVerb {
		// The cross-language wire contract for @query is a literal HTTP
		// QUERY method (matching the Go/TS/Python clients); reqwest accepts
		// arbitrary methods even though there is no .query() builder.
		p.P(`let mut request = self.http.request(reqwest::Method::from_bytes(b"QUERY").expect("QUERY is a valid HTTP method"), &url).headers(self.headers.clone());`)
	} else {
		p.P("let mut request = self.http.", verb, "(&url).headers(self.headers.clone());")
	}
	if onkir.IsBodyBearingVerb(verb) {
		if bodyField, ok := method.BodyField(); ok {
			if field := onkir.FindField(method.Request, bodyField); field != nil {
				if bodyFieldNeedsCustomWire(field) {
					writeBodyValue(p, field)
					p.P("request = request.json(&body_value);")
				} else {
					p.P("request = request.json(&req.", RustIdent(field.Name), ");")
				}
			} else {
				p.P("request = request.json(req);")
			}
		} else {
			p.P("request = request.json(req);")
		}
	} else {
		writeQueryParams(p, method.Request, pathFields)
		p.P("request = request.query(&query);")
	}
	if method.IsStream() {
		p.P("request = request.header(reqwest::header::ACCEPT, \"text/event-stream\");")
	}
	p.P("let response = request.send().await.map_err(", errorName, "::Transport)?;")
	p.P("let status = response.status();")
	p.P("if !status.is_success() {")
	p.Indent()
	p.P("let body = read_response_body(response, self.max_response_body_bytes).await.map_err(", errorName, "::Response)?;")
	writeTypedClientErrors(p, method, errorName)
	p.P(
		"return Err(", errorName,
		"::UnexpectedStatus { status: status.as_u16(), ",
		"body: String::from_utf8_lossy(&body).into_owned() });",
	)
	p.Dedent()
	p.P("}")
	if method.IsStream() {
		p.P("let max_frame_bytes = self.max_sse_frame_bytes;")
		writeClientStreamResponse(p, responseType, errorName)
	} else {
		p.P("let body = read_response_body(response, self.max_response_body_bytes).await.map_err(", errorName, "::Response)?;")
		p.P("serde_json::from_slice(&body).map_err(", errorName, "::Decode)")
	}
	p.Dedent()
	p.P("}")
	p.Blank()
}

func fileNeedsBodyWireEncoding(file *onkir.File) bool {
	for _, service := range file.Services {
		for _, method := range service.Methods {
			bodyName, ok := method.BodyField()
			if !ok {
				continue
			}
			if field := onkir.FindField(method.Request, bodyName); field != nil && bodyFieldNeedsCustomWire(field) {
				return true
			}
		}
	}
	return false
}

func bodyFieldNeedsCustomWire(field *onkir.Field) bool {
	return needsInt64StringEncoding(field) || needsEnumNumberEncoding(field) ||
		(field.Type != nil && field.Type.Kind == onkir.KindScalar && field.Type.Scalar == onkir.ScalarBytes)
}

func writeBodyValue(p *Printer, field *onkir.Field) {
	fieldExpr := "req." + RustIdent(field.Name)
	if field.Optional {
		p.P("let body_value = ", fieldExpr, ".as_ref().map(|value| ", rustBodyValueExpr(p, field, "value"), ").unwrap_or(serde_json::Value::Null);")
		return
	}
	p.P("let body_value = ", rustBodyValueExpr(p, field, "&"+fieldExpr), ";")
}

func rustBodyValueExpr(p *Printer, field *onkir.Field, expr string) string {
	switch {
	case needsInt64StringEncoding(field):
		return "serde_json::Value::String((*" + expr + ").to_string())"
	case needsEnumNumberEncoding(field):
		return "serde_json::Value::Number((" + rustEnumNumberExpr(p, field.Type.Enum, expr) + ").into())"
	case field.Type != nil && field.Type.Kind == onkir.KindScalar && field.Type.Scalar == onkir.ScalarBytes:
		return "serde_json::Value::String(" + rustBytesEncodeExpr(fieldEncoding(field), expr) + ")"
	default:
		return "serde_json::to_value(" + expr + ").expect(\"generated body value must serialize\")"
	}
}

func rustEnumNumberExpr(p *Printer, enum *onkir.Enum, expr string) string {
	var b strings.Builder
	b.WriteString("match ")
	b.WriteString(expr)
	b.WriteString(" {")
	for _, value := range enum.Values {
		b.WriteString(" ")
		b.WriteString(p.EnumTypeName(enum))
		b.WriteString("::")
		b.WriteString(PascalCase(value.Name))
		b.WriteString(" => ")
		b.WriteString(strconv.Itoa(value.Index))
		b.WriteString(",")
	}
	b.WriteString(" }")
	return b.String()
}

func rustBytesEncodeExpr(encoding, expr string) string {
	switch encoding {
	case "hex":
		return "(" + expr + ").iter().map(|byte| format!(\"{byte:02x}\")).collect::<String>()"
	case "base64_raw":
		return "base64::engine::general_purpose::STANDARD_NO_PAD.encode(" + expr + ")"
	case "base64url":
		return "base64::engine::general_purpose::URL_SAFE.encode(" + expr + ")"
	case "base64url_raw":
		return "base64::engine::general_purpose::URL_SAFE_NO_PAD.encode(" + expr + ")"
	default:
		return "base64::engine::general_purpose::STANDARD.encode(" + expr + ")"
	}
}

func writeQueryParams(p *Printer, request *onkir.Message, pathFields []string) {
	pathSet := map[string]bool{}
	for _, field := range pathFields {
		pathSet[field] = true
	}
	p.P("#[allow(unused_mut)]")
	p.P("let mut query: Vec<(&str, String)> = Vec::new();")
	for _, field := range request.Fields {
		if pathSet[field.Name] || field.Oneof != nil {
			continue
		}
		queryDecorator, ok := field.Decorator("query")
		if !ok || field.Type == nil || field.Type.Kind != onkir.KindScalar {
			continue
		}
		queryName, _ := queryDecorator.Value()
		if queryName == "" {
			queryName = field.Name
		}
		access := "req." + RustIdent(field.Name)
		switch {
		case field.Optional:
			p.P("if let Some(value) = &", access, " { query.push((", strconv.Quote(queryName), ", query_value(value))); }")
		case field.Repeated:
			p.P("for value in &", access, " { query.push((", strconv.Quote(queryName), ", query_value(value))); }")
		default:
			p.P("query.push((", strconv.Quote(queryName), ", query_value(&", access, ")));")
		}
	}
}

func writeTypedClientErrors(p *Printer, method *onkir.Method, errorName string) {
	variants := ErrorVariantNames(method.ErrorTypes)
	for i, errorType := range method.ErrorTypes {
		status := 500
		if code, ok := errorType.StatusCode(); ok {
			status = code
		}
		p.P("if status.as_u16() == ", status, " {")
		p.Indent()
		p.P("let error = serde_json::from_slice(&body).map_err(", errorName, "::Decode)?;")
		p.P("return Err(", errorName, "::", variants[i], "(error));")
		p.Dedent()
		p.P("}")
	}
}

func writeClientStreamResponse(p *Printer, responseType, errorName string) {
	p.P("Ok(async_stream::stream! {")
	p.Indent()
	p.P("let mut chunks = response.bytes_stream();")
	p.P("let mut buffer = String::new();")
	p.P("while let Some(chunk) = chunks.next().await {")
	p.Indent()
	p.P("match chunk {")
	p.Indent()
	p.P("Err(error) => { yield Err(", errorName, "::Transport(error)); break; }")
	p.P("Ok(chunk) => {")
	p.Indent()
	p.P("buffer.push_str(&String::from_utf8_lossy(&chunk));")
	p.P("if buffer.len() > max_frame_bytes { yield Err(", errorName, "::Response(\"SSE frame exceeds configured limit\".into())); break; }")
	p.P("while let Some(boundary) = buffer.find(\"\\n\\n\") {")
	p.Indent()
	p.P("let frame = buffer[..boundary].to_owned();")
	p.P("buffer.drain(..boundary + 2);")
	p.P("let mut event = \"message\";")
	p.P("let mut data = String::new();")
	p.P("for line in frame.lines() {")
	p.Indent()
	p.P("if let Some(value) = line.strip_prefix(\"event:\") { event = value.trim(); }")
	p.P("if let Some(value) = line.strip_prefix(\"data:\") {")
	p.Indent()
	p.P("if !data.is_empty() { data.push('\\n'); }")
	p.P("data.push_str(value.trim_start());")
	p.Dedent()
	p.P("}")
	p.Dedent()
	p.P("}")
	p.P("if event == \"error\" {")
	p.Indent()
	p.P("yield Err(", errorName, "::Stream(data));")
	p.P("continue;")
	p.Dedent()
	p.P("}")
	p.P("if !data.is_empty() { yield serde_json::from_str::<", responseType, ">(&data).map_err(", errorName, "::Decode); }")
	p.Dedent()
	p.P("}")
	p.Dedent()
	p.P("}")
	p.Dedent()
	p.P("}")
	p.Dedent()
	p.P("}")
	p.Dedent()
	p.P("})")
}

func writeClientError(p *Printer, service *onkir.Service, method *onkir.Method) {
	name := clientErrorName(service, method)
	p.P("#[derive(Debug)]")
	p.P("pub enum ", name, " {")
	p.Indent()
	p.P("Validation(ValidationError),")
	p.P("InvalidRequest(String),")
	p.P("Transport(reqwest::Error),")
	p.P("Response(String),")
	p.P("Decode(serde_json::Error),")
	if method.IsStream() {
		p.P("Stream(String),")
	}
	variants := ErrorVariantNames(method.ErrorTypes)
	for i, errorType := range method.ErrorTypes {
		p.P(variants[i], "(", p.MessageTypeName(errorType), "),")
	}
	p.P("UnexpectedStatus { status: u16, body: String },")
	p.Dedent()
	p.P("}")
	p.Blank()
	p.P("impl std::fmt::Display for ", name, " {")
	p.Indent()
	p.P("fn fmt(&self, formatter: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {")
	p.Indent()
	p.P("match self {")
	p.Indent()
	p.P("Self::Validation(error) => write!(formatter, \"request validation failed: {error}\"),")
	p.P("Self::InvalidRequest(error) => write!(formatter, \"invalid request: {error}\"),")
	p.P("Self::Transport(error) => write!(formatter, \"HTTP transport failed: {error}\"),")
	p.P("Self::Response(error) => write!(formatter, \"response failed: {error}\"),")
	p.P("Self::Decode(error) => write!(formatter, \"response decoding failed: {error}\"),")
	if method.IsStream() {
		p.P("Self::Stream(error) => write!(formatter, \"stream failed: {error}\"),")
	}
	for i, errorType := range method.ErrorTypes {
		p.P("Self::", variants[i], "(error) => write!(formatter, \"", errorType.Name, ": {error}\"),")
	}
	p.P("Self::UnexpectedStatus { status, body } => write!(formatter, \"unexpected HTTP status {status}: {body}\"),")
	p.Dedent()
	p.P("}")
	p.Dedent()
	p.P("}")
	p.Dedent()
	p.P("}")
	p.P("impl std::error::Error for ", name, " {}")
	p.Blank()
}

func clientErrorName(service *onkir.Service, method *onkir.Method) string {
	return PascalCase(service.Name) + PascalCase(method.Name) + "Error"
}

func pathFieldNames(path string) []string {
	var names []string
	start := -1
	for index, char := range path {
		switch {
		case char == '{':
			start = index + 1
		case char == '}' && start >= 0:
			names = append(names, path[start:index])
			start = -1
		}
	}
	return names
}
