package genrust

import (
	"strconv"
	"strings"

	"github.com/1homsi/onekit/internal/onkir"
)

type typeFeatures struct {
	bytes     bool
	intString bool
	email     bool
	empty     bool
}

func GenerateTypes(file *onkir.File) []byte {
	return GenerateTypesWithResolver(file, nil)
}

func GenerateTypesWithResolver(file *onkir.File, resolver PackageResolver) []byte {
	p := newPrinter(resolver)
	features := collectTypeFeatures(file)

	p.P("// Code generated by onek. DO NOT EDIT.")
	p.P("#![allow(clippy::derive_partial_eq_without_eq)]")
	p.Blank()
	p.P("#[allow(unused_imports)]")
	p.P("use serde::{Deserialize, Deserializer, Serialize, Serializer};")
	if features.bytes {
		p.P("use base64::Engine as _;")
	}
	if features.email {
		p.P("use validator::ValidateEmail as _;")
	}
	p.Blank()

	writeValidationError(p)
	writeSerdeHelpers(p, features)

	for _, enum := range file.Enums {
		writeEnum(p, enum)
	}
	for _, message := range file.Messages {
		writeMessageTree(p, message)
	}
	return p.Bytes()
}

func collectTypeFeatures(file *onkir.File) typeFeatures {
	var features typeFeatures
	var inspectMessage func(*onkir.Message)
	inspectMessage = func(message *onkir.Message) {
		for _, field := range message.Fields {
			if field.Type != nil && field.Type.Kind == onkir.KindScalar {
				if field.Type.Scalar == onkir.ScalarBytes {
					features.bytes = true
				}
				if (field.Type.Scalar == onkir.ScalarInt64 || field.Type.Scalar == onkir.ScalarUint64) &&
					fieldEncoding(field) != rustEncodeNumber {
					features.intString = true
				}
			}
			if field.Type != nil && field.Type.Kind == onkir.KindMap && field.Type.MapValue != nil &&
				field.Type.MapValue.Kind == onkir.KindScalar && field.Type.MapValue.Scalar == onkir.ScalarBytes {
				features.bytes = true
			}
			if emptyBehavior(field) != "" {
				features.empty = true
			}
			for _, decorator := range field.Decorators {
				if decorator.Name == decoratorEmail {
					features.email = true
				}
			}
		}
		for _, nested := range message.Nested {
			inspectMessage(nested)
		}
	}
	for _, message := range file.Messages {
		inspectMessage(message)
	}
	return features
}

func writeValidationError(p *Printer) {
	p.P("#[derive(Debug, Clone, PartialEq, Eq)]")
	p.P("pub struct ValidationError {")
	p.Indent()
	p.P("pub field: &'static str,")
	p.P("pub message: String,")
	p.Dedent()
	p.P("}")
	p.Blank()
	p.P("impl std::fmt::Display for ValidationError {")
	p.Indent()
	p.P("fn fmt(&self, formatter: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {")
	p.Indent()
	p.P("write!(formatter, \"{}: {}\", self.field, self.message)")
	p.Dedent()
	p.P("}")
	p.Dedent()
	p.P("}")
	p.Blank()
	p.P("impl std::error::Error for ValidationError {}")
	p.Blank()
}

func writeSerdeHelpers(p *Printer, features typeFeatures) {
	if features.intString {
		writeIntegerStringModules(p)
	}
	if features.bytes {
		writeBytesModules(p)
	}
	if features.empty {
		p.P("fn is_none_or_empty<T: Serialize>(value: &Option<Box<T>>) -> bool {")
		p.Indent()
		p.P("match value {")
		p.Indent()
		p.P("None => true,")
		p.P("Some(value) => serde_json::to_value(value)")
		p.Indent()
		p.P(".map(|value| value.as_object().is_some_and(|object| object.is_empty()))")
		p.P(".unwrap_or(false),")
		p.Dedent()
		p.Dedent()
		p.P("}")
		p.Dedent()
		p.P("}")
		p.Blank()
		p.P("fn serialize_empty_as_null<T: Serialize, S: Serializer>(")
		p.Indent()
		p.P("value: &Option<Box<T>>,")
		p.P("serializer: S,")
		p.Dedent()
		p.P(") -> Result<S::Ok, S::Error> {")
		p.Indent()
		p.P("match value {")
		p.Indent()
		p.P("None => serializer.serialize_none(),")
		p.P("Some(value) => {")
		p.Indent()
		p.P("let value = serde_json::to_value(value).map_err(serde::ser::Error::custom)?;")
		p.P("if value.as_object().is_some_and(|object| object.is_empty()) {")
		p.Indent()
		p.P("serializer.serialize_none()")
		p.Dedent()
		p.P("} else {")
		p.Indent()
		p.P("value.serialize(serializer)")
		p.Dedent()
		p.P("}")
		p.Dedent()
		p.P("}")
		p.Dedent()
		p.P("}")
		p.Dedent()
		p.P("}")
		p.Blank()
	}
}

func writeIntegerStringModules(p *Printer) {
	for _, spec := range []struct {
		name string
		typ  string
	}{
		{"i64_string", "i64"},
		{"u64_string", "u64"},
	} {
		p.P("#[allow(dead_code)]")
		p.P("mod serde_", spec.name, " {")
		p.Indent()
		p.P("use super::*;")
		p.P("pub fn serialize<S: Serializer>(value: &", spec.typ, ", serializer: S) -> Result<S::Ok, S::Error> {")
		p.Indent()
		p.P("serializer.serialize_str(&value.to_string())")
		p.Dedent()
		p.P("}")
		p.P("pub fn deserialize<'de, D: Deserializer<'de>>(deserializer: D) -> Result<", spec.typ, ", D::Error> {")
		p.Indent()
		p.P("let value = String::deserialize(deserializer)?;")
		p.P("value.parse().map_err(serde::de::Error::custom)")
		p.Dedent()
		p.P("}")
		p.Dedent()
		p.P("}")
		p.Blank()

		p.P("#[allow(dead_code)]")
		p.P("mod serde_option_", spec.name, " {")
		p.Indent()
		p.P("use super::*;")
		p.P(
			"pub fn serialize<S: Serializer>(value: &Option<",
			spec.typ,
			">, serializer: S) -> Result<S::Ok, S::Error> {",
		)
		p.Indent()
		p.P("value.map(|value| value.to_string()).serialize(serializer)")
		p.Dedent()
		p.P("}")
		p.P(
			"pub fn deserialize<'de, D: Deserializer<'de>>(deserializer: D) -> Result<Option<",
			spec.typ,
			">, D::Error> {",
		)
		p.Indent()
		p.P("Option::<String>::deserialize(deserializer)?")
		p.Indent()
		p.P(".map(|value| value.parse().map_err(serde::de::Error::custom))")
		p.P(".transpose()")
		p.Dedent()
		p.Dedent()
		p.P("}")
		p.Dedent()
		p.P("}")
		p.Blank()

		p.P("#[allow(dead_code)]")
		p.P("mod serde_vec_", spec.name, " {")
		p.Indent()
		p.P("use super::*;")
		p.P("pub fn serialize<S: Serializer>(value: &[", spec.typ, "], serializer: S) -> Result<S::Ok, S::Error> {")
		p.Indent()
		p.P("value.iter().map(ToString::to_string).collect::<Vec<_>>().serialize(serializer)")
		p.Dedent()
		p.P("}")
		p.P("pub fn deserialize<'de, D: Deserializer<'de>>(deserializer: D) -> Result<Vec<", spec.typ, ">, D::Error> {")
		p.Indent()
		p.P("Vec::<String>::deserialize(deserializer)?")
		p.Indent()
		p.P(".into_iter()")
		p.P(".map(|value| value.parse().map_err(serde::de::Error::custom))")
		p.P(".collect()")
		p.Dedent()
		p.Dedent()
		p.P("}")
		p.Dedent()
		p.P("}")
		p.Blank()
	}
}

func writeBytesModules(p *Printer) {
	encodings := []struct {
		name       string
		encodeExpr string
		decodeExpr string
	}{
		{
			"base64",
			"base64::engine::general_purpose::STANDARD.encode(value)",
			"base64::engine::general_purpose::STANDARD.decode(value)",
		},
		{
			"base64_raw",
			"base64::engine::general_purpose::STANDARD_NO_PAD.encode(value)",
			"base64::engine::general_purpose::STANDARD_NO_PAD.decode(value)",
		},
		{
			"base64_url",
			"base64::engine::general_purpose::URL_SAFE.encode(value)",
			"base64::engine::general_purpose::URL_SAFE.decode(value)",
		},
		{
			"base64_url_raw",
			"base64::engine::general_purpose::URL_SAFE_NO_PAD.encode(value)",
			"base64::engine::general_purpose::URL_SAFE_NO_PAD.decode(value)",
		},
	}
	for _, encoding := range encodings {
		writeBytesModule(p, "serde_bytes_"+encoding.name, encoding.encodeExpr, encoding.decodeExpr)
		writeOptionalBytesModule(p, "serde_option_bytes_"+encoding.name, encoding.encodeExpr, encoding.decodeExpr)
		writeRepeatedBytesModule(p, "serde_vec_bytes_"+encoding.name, encoding.encodeExpr, encoding.decodeExpr)
	}
	hexEncode := `value.iter().map(|byte| format!("{byte:02x}")).collect::<String>()`
	hexDecode := `decode_hex(value)`
	writeHexDecodeHelper(p)
	writeBytesModule(p, "serde_bytes_hex", hexEncode, hexDecode)
	writeOptionalBytesModule(p, "serde_option_bytes_hex", hexEncode, hexDecode)
	writeRepeatedBytesModule(p, "serde_vec_bytes_hex", hexEncode, hexDecode)
}

func writeBytesModule(p *Printer, name, encodeExpr, decodeExpr string) {
	p.P("#[allow(dead_code)]")
	p.P("mod ", name, " {")
	p.Indent()
	p.P("use super::*;")
	p.P("pub fn serialize<S: Serializer>(value: &[u8], serializer: S) -> Result<S::Ok, S::Error> {")
	p.Indent()
	p.P(encodeExpr, ".serialize(serializer)")
	p.Dedent()
	p.P("}")
	p.P("pub fn deserialize<'de, D: Deserializer<'de>>(deserializer: D) -> Result<Vec<u8>, D::Error> {")
	p.Indent()
	p.P("let value = String::deserialize(deserializer)?;")
	p.P(decodeExpr, ".map_err(serde::de::Error::custom)")
	p.Dedent()
	p.P("}")
	p.Dedent()
	p.P("}")
	p.Blank()
}

